from typing import Optional

import zenoh

# Zenoh encoding stamped on every sample this publisher sends.
WIRE_TAG = "application/protobuf;ros2/std/StringStamped"

DEFAULT_DEVICE = "dev01"
DEFAULT_WORKSPACE = "demo"
DEFAULT_MODULE = "pubber"
DEFAULT_TOPIC = "hello"
TRANSPORT_SEGMENT = "zenoh"


class HelloPublisher:
    """Zenoh publisher wrapper. Pass an open `zenoh.Session`."""

    def __init__(
        self,
        session: zenoh.Session,
        device: Optional[str] = None,
        workspace: Optional[str] = None,
        module: Optional[str] = None,
        topic: Optional[str] = None,
        full: Optional[str] = None,
    ) -> None:
        if full is not None:
            # `full` short-circuits segment assembly — use the string verbatim.
            key = full
        else:
            key = "{}/{}/{}/{}/{}".format(
                device or DEFAULT_DEVICE,
                workspace or DEFAULT_WORKSPACE,
                module or DEFAULT_MODULE,
                TRANSPORT_SEGMENT,
                topic or DEFAULT_TOPIC,
            )
        self.key_expr = key
        self._publisher = session.declare_publisher(
            key,
            encoding=zenoh.Encoding(WIRE_TAG),
        )

    def publish(self, msg) -> None:
        """Serialize `msg` (a `StringStamped` from `StringStamped_pb2`) with
        ``SerializeToString()`` and publish it. Bytes you serialized
        yourself are published as-is, like ``publish_bytes``."""
        if isinstance(msg, (bytes, bytearray, memoryview)):
            self.publish_bytes(bytes(msg))
        else:
            self.publish_bytes(msg.SerializeToString())

    def publish_bytes(self, payload: bytes) -> None:
        """Publish bytes you produced yourself. The Zenoh encoding tag
        ``WIRE_TAG`` is set by this publisher."""
        self._publisher.put(payload)

    def close(self) -> None:
        self._publisher.undeclare()
